#!/usr/bin/env python3
"""Merge ONE gene's results from a single-gene re-run into an existing results
directory, and regenerate the summaries.

    python3 tools/merge_gene.py --gene bhp --from <rerun-dir> --into <results-dir>

Written for the bhp panel fix: the v4 bhp panel was 160-643 aa of ', partial'
fragments for a ~2,500 aa protein, so its one positive was a fragment being
called a gene. Re-running 55 genes to fix 1 costs ~13.5 h; re-running bhp alone
costs minutes, and this merges the result back.

WHAT IT TOUCHES, per sample:
    gene_presence_table_v2.csv   the gene's row, replaced
    gene_calls.tsv               the gene's row, replaced
    gene_presence_matrix.tsv     the gene's row, replaced
and then, once:
    summary/gene_presence_matrix.tsv   rebuilt by concatenation
    summary/gene_presence_matrix_wide.tsv
    summary/gene_prevalence.tsv        regenerated by bin/summarize_matrix.py
    summary/genes_per_genome.tsv

Everything is verified before anything is written, and the originals are kept
as <name>.pre-<gene>-merge. Safety rules, each from a bug that happened:

  * SAMPLE SETS MUST MATCH EXACTLY. A re-run over a different seedfile would
    otherwise silently drop or invent genomes.
  * HEADERS MUST MATCH EXACTLY. A re-run from different code writes different
    columns, and splicing those rows together produces a table whose columns
    mean different things in different rows.
  * THE GENE MUST BE PRESENT IN BOTH. A typo'd gene name would otherwise merge
    nothing and report success.
  * SUMMARIES ARE REGENERATED, NEVER EDITED. Hand-patching summary/ while
    globbing */ is what turned a matrix into 97 million rows once.
"""

import argparse
import csv
import os
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)

PER_SAMPLE = [
    ("gene_presence_table_v2.csv", ",",  "gene"),
    ("gene_calls.tsv",             "\t", "gene"),
    ("gene_presence_matrix.tsv",   "\t", "gene"),
]


def samples_in(d):
    return sorted(x for x in os.listdir(d)
                  if os.path.isdir(os.path.join(d, x))
                  and x not in ("summary", "protein_db")
                  and os.path.exists(os.path.join(d, x, "gene_calls.tsv")))


def read_rows(path, delim):
    with open(path, newline="") as fh:
        rd = csv.reader(fh, delimiter=delim)
        rows = list(rd)
    return rows[0], rows[1:]


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--gene", required=True)
    ap.add_argument("--from", dest="src", required=True,
                    help="single-gene re-run results directory")
    ap.add_argument("--into", dest="dst", required=True,
                    help="existing multi-gene results directory to patch")
    ap.add_argument("--genes", default=os.path.join(REPO, "genes_2_3.txt"),
                    help="gene list, for wide-matrix column order")
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    gene = args.gene
    src_s, dst_s = samples_in(args.src), samples_in(args.dst)

    # ── verify ─────────────────────────────────────────────────────────────
    problems = []
    if set(src_s) != set(dst_s):
        only_src, only_dst = set(src_s) - set(dst_s), set(dst_s) - set(src_s)
        problems.append(f"sample sets differ: only in re-run {sorted(only_src)}; "
                        f"only in target {sorted(only_dst)}")

    plan = []          # (sample, filename, delim, header, new_row, old_row)
    for s in sorted(set(src_s) & set(dst_s)):
        for fn, delim, keycol in PER_SAMPLE:
            ps = os.path.join(args.src, s, fn)
            pd_ = os.path.join(args.dst, s, fn)
            if not os.path.exists(ps) or not os.path.exists(pd_):
                problems.append(f"{s}/{fn}: missing in "
                                f"{'re-run' if not os.path.exists(ps) else 'target'}")
                continue
            hs, rs = read_rows(ps, delim)
            hd, rd_ = read_rows(pd_, delim)
            if hs != hd:
                problems.append(f"{s}/{fn}: header mismatch\n"
                                f"      re-run: {hs}\n      target: {hd}")
                continue
            gi = hd.index(keycol)
            new = [r for r in rs if r[gi] == gene]
            old = [r for r in rd_ if r[gi] == gene]
            if len(new) != 1:
                problems.append(f"{s}/{fn}: re-run has {len(new)} '{gene}' rows, expected 1")
            if len(old) != 1:
                problems.append(f"{s}/{fn}: target has {len(old)} '{gene}' rows, expected 1")
            if len(new) == 1 and len(old) == 1:
                plan.append((s, fn, delim, hd, rd_, gi, new[0], old[0]))

    if problems:
        print(f"REFUSING TO MERGE -- {len(problems)} problem(s):", file=sys.stderr)
        for p in problems[:20]:
            print(f"  - {p}", file=sys.stderr)
        return 1

    # A merged 'present' with no confirming accession would be WEAKER evidence
    # than the row it replaces: the target run verified every present call
    # (848/848 carry an accession), so a re-run launched without
    # --nr_verify_present true must not be spliced in beside it.
    unverified = []
    for s, fn, _, h, _, _, new, _ in plan:
        if fn == "gene_presence_table_v2.csv" and new[h.index("final_call")] == "present" \
           and not new[h.index("nr_confirming_accession")].strip():
            unverified.append(s)
    if unverified:
        print(f"REFUSING TO MERGE -- {len(unverified)} 'present' call(s) in the "
              f"re-run carry no nr evidence: {unverified}\n"
              f"  Re-run with --nr_verify_present true.", file=sys.stderr)
        return 1

    # ── what changes ───────────────────────────────────────────────────────
    changed = []
    for s, fn, _, h, _, _, new, old in plan:
        if fn == "gene_presence_table_v2.csv" and new != old:
            ci = h.index("final_call")
            changed.append((s, old[ci], new[ci],
                            old[h.index("round1_identity_pct")],
                            new[h.index("round1_identity_pct")],
                            old[h.index("round1_coverage_pct")],
                            new[h.index("round1_coverage_pct")]))

    print(f"gene '{gene}' across {len(set(src_s) & set(dst_s))} samples; "
          f"{len(changed)} table row(s) differ\n")
    if changed:
        print(f"  {'sample':<12} {'final_call':>22}   {'identity':>13}  {'coverage':>13}")
        for s, oc, nc, oi, ni, ov, nv in changed:
            print(f"  {s:<12} {oc:>9} -> {nc:<10}  {oi:>5} -> {ni:<5}  {ov:>5} -> {nv:<5}")
        print()
    if args.dry_run:
        print("--dry-run: nothing written")
        return 0

    # ── write ──────────────────────────────────────────────────────────────
    for s, fn, delim, h, rows, gi, new, old in plan:
        p = os.path.join(args.dst, s, fn)
        bak = f"{p}.pre-{gene}-merge"
        if not os.path.exists(bak):
            shutil.copy2(p, bak)
        out = [h] + [new if r[gi] == gene else r for r in rows]
        with open(p, "w", newline="") as fh:
            csv.writer(fh, delimiter=delim, lineterminator="\n").writerows(out)

    # ── summaries: rebuild, never patch ────────────────────────────────────
    summ = os.path.join(args.dst, "summary")
    long_m = os.path.join(summ, "gene_presence_matrix.tsv")
    bak = f"{long_m}.pre-{gene}-merge"
    if not os.path.exists(bak):
        shutil.copy2(long_m, bak)

    # Concatenate the PER-SAMPLE matrices explicitly by name. Never glob */ --
    # that includes summary/ and feeds the output back into itself.
    header, body = None, []
    for s in sorted(set(src_s) & set(dst_s)):
        h, r = read_rows(os.path.join(args.dst, s, "gene_presence_matrix.tsv"), "\t")
        header = header or h
        assert h == header, f"{s}: per-sample matrix header drift"
        body += r
    tmp = long_m + ".tmp"
    with open(tmp, "w", newline="") as fh:
        csv.writer(fh, delimiter="\t", lineterminator="\n").writerows([header] + body)
    os.replace(tmp, long_m)
    print(f"summary/gene_presence_matrix.tsv: {len(body)} rows")

    cmd = [sys.executable, os.path.join(REPO, "bin", "summarize_matrix.py"),
           "--matrix", long_m, "--out-prefix", summ]
    if os.path.exists(args.genes):
        cmd += ["--genes", args.genes]
    for f in ("gene_presence_matrix_wide.tsv", "gene_prevalence.tsv",
              "genes_per_genome.tsv"):
        p = os.path.join(summ, f)
        b = f"{p}.pre-{gene}-merge"
        if os.path.exists(p) and not os.path.exists(b):
            shutil.copy2(p, b)
    subprocess.run(cmd, check=True)

    # ── post-check ─────────────────────────────────────────────────────────
    n = sum(1 for r in body if r[1] == gene and r[2] == "1")
    tot = sum(1 for r in body if r[1] == gene)
    print(f"\n{gene}: {n}/{tot} genomes present after merge")
    print(f"originals kept as *.pre-{gene}-merge")
    return 0


if __name__ == "__main__":
    sys.exit(main())
